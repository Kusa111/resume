function cleanToken(token) {
  return String(token || '').replace(/^[^А-Яа-яЁё.…\.]+|[^А-Яа-яЁё.…\.]+$/g, '');
}

function inferAnswer(pattern, original) {
  const dotToken = String(pattern).split(/\s+/).find((part) => /[.…\.]{2,}/.test(part)) || pattern;
  const cleanPattern = cleanToken(dotToken);
  const [beforeRaw = '', afterRaw = ''] = cleanPattern.split(/[.…\.]+/);
  const before = key(beforeRaw);
  const after = key(afterRaw);
  const originalTokens = String(original).split(/\s+/).map(cleanToken).filter(Boolean);
  const match = originalTokens.find((token) => {
    const normalized = key(token);
    return normalized.startsWith(before) && normalized.endsWith(after) && normalized.length > before.length + after.length;
  }) || originalTokens.find((token) => key(token).includes(before)) || originalTokens[0] || original;
  return match.charAt(beforeRaw.length).toLowerCase();
}

function choicesFor(answer, mode, pattern) {
  const a = String(answer || '').toLowerCase();
  if (mode === 'prepri') return ['е', 'и'];
  if (mode.startsWith('task12') && /ущ|ющ/.test(pattern)) return ['у', 'ю'];
  if (mode.startsWith('task12') && /ащ|ящ/.test(pattern)) return ['а', 'я'];
  return CHOICES[key(a)] || ['е', 'и'];
}

function explicitTask(line, mode) {
  const [pattern, original] = line.split('|').map((part) => part.trim());
  const answer = inferAnswer(pattern, original);
  const masked = pattern.replace(/[.…\.]{2,}/, '_').replace(/\s+/g, ' ').trim();
  return make(original, masked, answer, choicesFor(answer, mode, pattern));
}

function explicitTasks(mode) {
  return (explicitLines[mode] || '').split('\n').map((line) => line.trim()).filter(Boolean).map((line) => explicitTask(line, mode));
}

