const splitWords = (key) => sources[key].split(',').map((word) => word.trim()).filter(Boolean);

const makeObject = (original, masked, answer, hint = '') => ({ original, masked, answer, hint });

const maskAt = (word, index, length = 1) => makeObject(
  word,
  `${word.slice(0, index)}_${word.slice(index + length)}`,
  word.slice(index, index + length),
);

const maskFirst = (word, regex, length = 1, offset = 0) => {
  const match = word.match(regex);
  if (!match || match.index === undefined) return null;
  return maskAt(word, match.index + offset, length);
};

const fallbackMask = (word) => {
  const index = word.search(/[аеёиоуыэюя]/iu);
  return maskAt(word, Math.max(index, 0));
};

function maskTask9(word) {
  const lower = word.toLowerCase();
  if (lower === 'пловец') return makeObject(word, 'пл_вец', 'о');
  if (/[ц]/i.test(word)) return maskFirst(word, /[ыи]/iu);
  if (/[жшчщ][ю]/iu.test(word)) return maskFirst(word, /[ю]/iu);
  if (/[жшчщ][оё]/iu.test(word)) return maskFirst(word, /[оё]/iu);
  if (/рост|рос|раст|отрасл|вырост|подрост/.test(lower)) return maskFirst(word, /[ао]/iu);
  if (/скак|скач|скоч/.test(lower)) return maskFirst(word, /[ао]/iu);
  if (/жиг|жег|жёг/.test(lower)) return maskFirst(word, /[иеё]/iu);
  if (/чет|чит/.test(lower)) return maskFirst(word, /[еи]/iu);
  if (/гар|гор/.test(lower)) return maskFirst(word, /[ао]/iu);
  if (/зар|зор/.test(lower)) return maskFirst(word, /[ао]/iu);
  if (/плав|плов|плыв/.test(lower)) return maskFirst(word, /[аоы]/iu) || fallbackMask(word);
  if (/мок|мак/.test(lower)) return maskFirst(word, /[ао]/iu);
  if (/равн|ровн|равни|ровес|уров|поров/.test(lower)) return maskFirst(word, /[ао]/iu);
  if (/жю|шю/.test(lower)) return maskFirst(word, /[ю]/iu);
  return fallbackMask(word);
}

function maskTask10(word) {
  const lower = word.toLowerCase();
  if (/[ъ]/u.test(word)) return maskFirst(word, /ъ/u);
  if (/безы|преды|поды|разы|обы/.test(lower)) return maskFirst(word, /[ыи]/iu);
  if (/инф|инв|иняз|иниц|постин|дезин|спортин|оргед/.test(lower)) return maskFirst(word, /[ыи]/iu);
  if (/^пре|^при/.test(lower)) return maskAt(word, 2);
  if (/^про/.test(lower)) return maskAt(word, 2);
  return fallbackMask(word);
}

function maskTask11(word) {
  const checks = [
    [/ева|ова|ыва|ива/iu, 1], [/евать|ивать|овать|ывать/iu, 1], [/евый|овый/iu, 1],
    [/[чщ]он/iu, 1], [/жёр|шён/iu, 1], [/ицын|ын/iu, 0], [/ость|ота|ина|ество/iu, 0],
    [/леять|таяли/iu, 1], [/силеть|силить/iu, 3], [/давна|лево|словно/iu, 1]
  ];
  for (const [regex, offset] of checks) {
    const masked = maskFirst(word, regex, 1, offset);
    if (masked) return masked;
  }
  return fallbackMask(word);
}

function maskTask12(word) {
  const checks = [
    [/ем|им/iu, 0], [/ущ|ющ|ащ|ящ/iu, 0], [/енн|анн|янн/iu, 0], [/евш|ивш|явш/iu, 0],
    [/еян|еяв|еял|таяв|чаяв/iu, 1], [/брезж/iu, 2], [/зижд/iu, 1]
  ];
  for (const [regex, offset] of checks) {
    const masked = maskFirst(word, regex, 1, offset);
    if (masked) return masked;
  }
  return fallbackMask(word);
}

function maskPrePri(original) {
  const answer = original.toLowerCase().includes('при') ? 'и' : 'е';
  const masked = original.replace(/пр[еи]/iu, 'пр_');
  const hint = prepriContexts[original] || (answer === 'е'
    ? 'ПРЕ-: близко к «пере-», высокая степень или словарное написание.'
    : 'ПРИ-: приближение, присоединение, близость, неполнота действия или словарное написание.');
  return makeObject(original, masked, answer, hint);
}

