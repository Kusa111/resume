function fromMap(text) {
  const item = exactMap[key(text)];
  return item ? make(text, item[0], item[1], item[2]) : null;
}

function maskAt(text, index, length = 1, choices) {
  const answer = text.slice(index, index + length).toLowerCase();
  return make(text, `${text.slice(0, index)}_${text.slice(index + length)}`, answer, choices || CHOICES[key(answer)] || ['а', 'о']);
}

function maskFirst(text, regex, choices, offset = 0, length = 1) {
  const match = text.match(regex);
  if (!match || match.index === undefined) return null;
  return maskAt(text, match.index + offset, length, choices);
}

function fallbackMask(text) {
  const matches = [...text.matchAll(/[аеёиоуыэюя]/giu)];
  const match = matches[Math.min(1, matches.length - 1)] || matches[0];
  if (!match || match.index === undefined) return make(text, text, '', ['а', 'о']);
  const answer = match[0].toLowerCase();
  return maskAt(text, match.index, 1, CHOICES[key(answer)] || ['а', 'о']);
}

function maskPrePri(text) {
  const match = text.match(/пр[еи]/iu);
  return match && match.index !== undefined ? maskAt(text, match.index + 2, 1, ['е', 'и']) : fallbackMask(text);
}

